#if FD_ENV_BANDS > 0
extern const float fd_env_sos[];        /* per band: 2 sections x (b0 b1 b2 a1 a2) */
extern const int16_t fd_env_bins[];     /* per band: 3 orders x 2 harmonics x (lo, hi) envelope bins */
#endif

