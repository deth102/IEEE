"""Generate the signal set for the hardware-in-the-loop (HIL) firmware (firmware/hil_esp32).

For every KAIST recording, W consecutive non-overlapping windows are taken from the start of the
fold-0 test block (never used to train the exported models). They are stored as int16 with the
dataset-wide ADC scale, together with the Python predictions of the exported models so that the
board can check itself.

usage: python -m tools.make_hil_data [--windows 5] [--tag kaist_n8192] [--aug-tag kaist_n8192_aug]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from fdedge.config import CODE_DIR, load_config
from fdedge.data import FeatureStore, blocked_ranges, load_signal
from fdedge.export_c import global_scale, to_int16
from fdedge.features import extract_features


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--windows", type=int, default=5)
    a = ap.parse_args()
    cfg = load_config()
    N = cfg.signal["window"]
    fs = float(cfg.kaist["fs"])
    band = cfg.kaist["shaft_band_hz"]
    st = FeatureStore(cfg, "kaist", N)
    scale = global_scale(max(float(np.max(np.abs(load_signal(r, cfg)))) for r in st.recs))

    from tools.hil_models import train_models
    models = train_models(cfg, st)                     # {"clean": (rf, sm), "aug": (rf, sm)}

    recs, blobs = [], []
    for ri, r in enumerate(st.recs):
        x = np.asarray(load_signal(r, cfg), dtype=np.float32)
        lo, hi = blocked_ranges(r.length, cfg.protocol["n_folds"], 0)[2][0]     # fold-0 test block
        n_samp = a.windows * N
        assert lo + n_samp <= hi
        q = to_int16(x[lo:lo + n_samp], scale)
        W = q.reshape(a.windows, N).astype(np.float32) * np.float32(scale)
        F = extract_features(W, fs, band_hz=band)
        pred = {k: {"rf": m[0].predict(F).tolist(), "sm": m[1].predict(F).tolist()} for k, m in models.items()}
        peak = int(np.max(np.abs(q)))
        recs.append({"name": r.name, "load": r.load, "label": int(r.cls), "peak": peak, "pred": pred})
        blobs.append(q)

    out = CODE_DIR / "firmware" / "hil_esp32" / "include"
    out.mkdir(parents=True, exist_ok=True)
    lines = ["/* Generated by tools/make_hil_data.py — HIL signal set (fold-0 test blocks). */",
             "#pragma once", "#include <stdint.h>",
             f"#define HIL_N_REC {len(recs)}", f"#define HIL_WIN_PER_REC {a.windows}",
             f"#define HIL_SCALE {scale:.9g}f", ""]
    for i, q in enumerate(blobs):
        body = ",".join(str(int(v)) for v in q)
        lines.append(f"static const int16_t hil_sig_{i}[{len(q)}] = {{{body}}};")
    lines.append("static const int16_t *const hil_sig[HIL_N_REC] = {" +
                 ", ".join(f"hil_sig_{i}" for i in range(len(recs))) + "};")
    lines.append("static const char *const hil_name[HIL_N_REC] = {" + ", ".join(f'"{r["name"]}"' for r in recs) + "};")
    lines.append("static const uint8_t hil_label[HIL_N_REC] = {" + ", ".join(str(r["label"]) for r in recs) + "};")
    lines.append("static const int16_t hil_peak[HIL_N_REC] = {" + ", ".join(str(r["peak"]) for r in recs) + "};")
    for k in models:
        for m in ("rf", "sm"):
            flat = [p for r in recs for p in r["pred"][k][m]]
            lines.append(f"static const int8_t hil_py_{k}_{m}[HIL_N_REC * HIL_WIN_PER_REC] = {{" +
                         ", ".join(str(v) for v in flat) + "};")
    (out / "hil_data.h").write_text("\n".join(lines) + "\n", encoding="utf-8")
    meta = {"windows_per_rec": a.windows, "scale": scale, "recordings": recs}
    (out / "hil_data.json").write_text(json.dumps(meta, indent=1), encoding="utf-8")
    print(f"{len(recs)} recordings x {a.windows} windows -> {out / 'hil_data.h'} "
          f"({len(recs) * a.windows * N * 2 / 1e6:.2f} MB of int16)")


if __name__ == "__main__":
    main()
