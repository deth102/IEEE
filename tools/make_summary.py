"""Collect the headline numbers of every experiment into results/SUMMARY.md."""
from __future__ import annotations

import json

import pandas as pd

from fdedge.config import load_config

cfg = load_config()
T = cfg.path("results_dir") / "tables"
L = cfg.path("results_dir") / "logs"


def md(df: pd.DataFrame, floatfmt="{:.3f}") -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(floatfmt.format(v) if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(out)


def pm(df, m="f1"):
    df = df.copy()
    df[m.upper()] = [f"{a:.3f} ± {b:.3f}" for a, b in zip(df[f"{m}_mean"], df[f"{m}_std"].fillna(0))]
    return df


def load(name):
    p = T / f"{name}.csv"
    return pd.read_csv(p) if p.exists() else None


sections = []


def add(title, text):
    sections.append(f"## {title}\n\n{text}\n")


if (d := load("e01_protocol_summary")) is not None:
    add("E01 — protocol and feature set (KAIST, macro-F1)", md(pm(d)[["protocol", "model", "features", "F1"]]))
if (d := load("e01_protocol_cwru_summary")) is not None:
    add("E01 — CWRU", md(pm(d)[["protocol", "model", "features", "F1"]]))
if (d := load("e03_features_summary")) is not None:
    add("E03 — feature ablation (blocked)", md(pm(d)[["features", "model", "n_features", "arith_ops", "F1"]], "{:.0f}"))
if (d := load("e04_crossload_overview")) is not None:
    add("E04 — cross-load (KAIST)", md(pm(d)[["setting", "model", "features", "F1"]]))
if (d := load("e05_adaptation_summary")) is not None:
    d = d[d.k.isin([0, 1, 5])]
    add("E05 — adaptation to an unseen load (KAIST)", md(pm(d)[["setting", "model", "method", "k", "F1"]]))
if (d := load("e05_adaptation_cwru_summary")) is not None:
    d = d[d.k.isin([0, 5])]
    add("E05 — adaptation (CWRU)", md(pm(d)[["setting", "model", "method", "k", "F1"]]))
if (d := load("e05_adaptation_finetune_cost")) is not None:
    add("E05 — on-device fine-tuning cost (200 epochs)", md(d[d.platform.isin(["esp32", "stm32f446"])], "{:.2f}"))
if (d := load("e06_window_sweep_accuracy")) is not None:
    add("E06 — window length vs accuracy", md(pm(d)[["N", "model", "F1"]]))
if (d := load("e06_window_sweep_resources")) is not None:
    d = d[(d.platform == "esp32") & (d.model == "RF")][["N", "variant", "ram_bytes", "flash_bytes", "latency_ms", "rtf", "fits_sram"]]
    add("E06 — resources on ESP32 (estimated latency)", md(d, "{:.3f}"))
if (d := load("e07_voting_noise_voting")) is not None:
    add("E07 — majority voting (F19)", md(pm(d[(d.features == "F19") & d.V.isin([1, 5, 15])])[["model", "V", "decision_s", "F1"]]))
if (d := load("e07_voting_noise_noise")) is not None:
    add("E07 — noise robustness (F19)", md(pm(d[d.features == "F19"])[["model", "snr_db", "F1"]]))
if (d := load("e08_compression_formats")) is not None:
    add("E08 — compression", md(pm(d)[["model", "variant", "flash_bytes", "F1"]], "{:.0f}"))
if (d := load("e09_cnn_accuracy")) is not None:
    add("E09 — CNN baselines (accuracy)", md(pm(d)[["model", "setting", "F1"]]))
if (d := load("e09_cnn_cost")) is not None:
    add("E09 — CNN vs feature pipeline cost (per 0.32-s decision)", md(d[d.platform == "esp32"], "{:.2f}"))
if (d := load("e11_resources_platform_summary")) is not None:
    add("E11 — platform estimates, N = 8192", md(d[d.model == "RF"].drop(columns=["model"]), "{:.3f}"))
if (p := L / "e11_resources_elf_validation.json").exists():
    v = json.loads(p.read_text())
    add("E11 — memory model validation (thesis ELF)",
        f"measured buffers {v['measured_buffers_bytes']} B vs model {v['model_buffers_bytes']} B")
if (d := load("e12_export_golden")) is not None:
    add("E12 — C vs Python golden test", md(d, "{:.3g}"))
if (d := load("e13_firmware_memory")) is not None:
    add("E13 — cross-compiled firmware memory", md(d, "{:.0f}"))

out = cfg.path("results_dir") / "SUMMARY.md"
out.write_text("# Results summary (auto-generated by tools/make_summary.py)\n\n" + "\n".join(sections), encoding="utf-8")
print(f"-> {out} ({len(sections)} sections)")
